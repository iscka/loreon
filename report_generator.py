def extract_filter_params(filter_report_path, cli_min_len, cli_max_len, mapping_data):
    """Build a dict of analysis parameters for the report header.

    Length filter values come from CLI args or, as fallback, from the
    filter-report filename (e.g. report_filtering_1000_3000.tsv).
    Quality filter values come from mapping_stats.json when available.
    """
    import re

    params = {}

    # --- Length filter ---
    min_len = cli_min_len
    max_len = cli_max_len

    # Fallback: parse from filename  report_filtering_<min>_<max>.tsv
    if min_len is None or max_len is None:
        m = re.search(r'report_filtering_(\d+)_(\d+)', str(filter_report_path))
        if m:
            if min_len is None:
                min_len = int(m.group(1))
            if max_len is None:
                max_len = int(m.group(2))

    if min_len is not None and max_len is not None:
        # Treat 0/999999 as "disabled"
        len_active = not (min_len == 0 and max_len >= 999999)
        params['len_filter_active'] = len_active
        params['min_len'] = min_len
        params['max_len'] = max_len
    else:
        params['len_filter_active'] = None   # unknown
        params['min_len'] = None
        params['max_len'] = None

    # --- Quality filter (from mapping_stats.json) ---
    if mapping_data:
        mp = mapping_data.get('parameters', {})
        min_id = mp.get('min_percent_identity', 0.0)
        min_cov = mp.get('min_ref_coverage', 0.0)
    else:
        min_id = 0.0
        min_cov = 0.0

    params['quality_filter_active'] = min_id > 0 or min_cov > 0
    params['min_percent_identity'] = min_id
    params['min_ref_coverage'] = min_cov

    return params


def load_mapping_stats(mapping_stats_path):
    """Load mapping_stats.json if present, return (stats_dict, error_msg)."""
    if not mapping_stats_path:
        return None, None
    try:
        with open(mapping_stats_path, 'r', encoding='utf-8') as f:
            data = json.load(f)
        print(f"Mapping stats loaded from: {mapping_stats_path}")
        return data, None
    except Exception as e:
        msg = f"WARNING: Cannot read mapping stats file: {e}"
        print(msg, file=sys.stderr)
        return None, msg


def get_mapping_kpis(mapping_data):
    """Compute mapping KPI cards from mapping_stats dict."""
    summary = mapping_data.get('summary', {})
    params = mapping_data.get('parameters', {})
    total = summary.get('total_reads_all', 0)
    mapped = summary.get('total_mapped_all', 0)
    filtered = summary.get('total_after_quality_filter', 0)
    mapping_rate = summary.get('overall_mapping_rate_pct', 0.0)
    retention = summary.get('overall_quality_retention_pct', 100.0)
    min_id = params.get('min_percent_identity', 0.0)
    min_cov = params.get('min_ref_coverage', 0.0)
    quality_filter_active = min_id > 0 or min_cov > 0
    return {
        'total_reads': f"{total:,}",
        'mapped_reads': f"{mapped:,}",
        'mapping_rate': f"{mapping_rate:.1f}%",
        'reads_after_quality_filter': f"{filtered:,}",
        'quality_retention': f"{retention:.1f}%",
        'quality_filter_active': quality_filter_active,
        'min_percent_identity': min_id,
        'min_ref_coverage': min_cov,
    }


def get_taxquality_kpis(mapping_data):
    """Aggregate the taxonomic-quality / noise blocks (Features A & C) into
    report KPI values.  Returns None when no sample carries these blocks.

    Every value reports what was actually MEASURED.  Cards for measurements
    that did not run are suppressed rather than defaulted to zero — a
    fabricated "0.0% chimeras" is indistinguishable from a genuinely clean run
    and is the most dangerous thing this report could print.
    """
    samples = mapping_data.get('samples', [])
    params = mapping_data.get('parameters', {})

    has_resolution = any('taxonomic_quality' in s for s in samples)
    has_noise = any('noise' in s for s in samples)
    has_supp = any('supplementary_count' in s for s in samples)
    if not (has_resolution or has_noise or has_supp):
        return None

    # --- Resolution (read-weighted across samples) ---
    tot_reads = 0
    species_reads = 0.0
    support_weighted = 0.0
    for s in samples:
        tq = s.get('taxonomic_quality')
        if not tq:
            continue
        n = tq.get('n_reads', 0)
        tot_reads += n
        species_reads += tq.get('pct_reads_species', 0.0) / 100.0 * n
        support_weighted += tq.get('mean_support', 0.0) * n
    pct_species = round(species_reads / tot_reads * 100, 1) if tot_reads else 0.0
    mean_support = round(support_weighted / tot_reads, 3) if tot_reads else 0.0

    # --- Noise / chimera ---
    # Tier 2 (per-read, from the read-level pass) and Tier 1 (flagstat
    # segments) are DIFFERENT quantities and are reported under different
    # labels; they are never silently substituted for one another.
    split_pct = None
    split_label = None
    chimera_refined = None
    if has_noise:
        tot_mapped = sum(s['noise'].get('n_mapped_reads', 0)
                         for s in samples if 'noise' in s)
        split_reads = sum(s['noise'].get('split_reads', 0)
                          for s in samples if 'noise' in s)
        split_pct = round(split_reads / tot_mapped * 100, 2) if tot_mapped else 0.0
        split_label = 'Split / Chimeric Reads'
        if any(s['noise'].get('refined_available') for s in samples if 'noise' in s):
            chim = sum(s['noise'].get('n_candidate_chimeras', 0)
                       for s in samples if 'noise' in s)
            chimera_refined = round(chim / tot_mapped * 100, 2) if tot_mapped else 0.0
    elif has_supp:
        # Segments per mapped read — NOT a fraction of reads, and it can exceed
        # 100% when reads split into 3+ pieces.  Labelled accordingly.
        tot_mapped = sum(s.get('mapped_unfiltered', 0) for s in samples)
        supp = sum(s.get('supplementary_count', 0) for s in samples)
        split_pct = round(supp / tot_mapped * 100, 2) if tot_mapped else 0.0
        split_label = 'Supplementary Segments per Mapped Read'

    # --- EM diagnostics (surfaced so a non-converged run is visible) ---
    em_blocks = [s['em'] for s in samples if 'em' in s]
    em_info = None
    if em_blocks:
        n_reads = sum(b.get('n_reads', 0) for b in em_blocks)
        mass = sum(b.get('counts_total', 0.0) for b in em_blocks)
        em_info = {
            'all_converged': all(b.get('converged') for b in em_blocks),
            'not_converged_samples': [
                s['sample'] for s in samples
                if 'em' in s and not s['em'].get('converged')],
            'max_iterations': max(b.get('iterations', 0) for b in em_blocks),
            'reads': n_reads,
            'mass_assigned': round(mass, 2),
            'mass_conserved': abs(mass - n_reads) < max(1.0, 0.001 * n_reads),
            'reads_unassignable': sum(b.get('reads_unassignable', 0) for b in em_blocks),
        }

    # Reads excluded by the quality filter before the quality/EM pass — proves
    # the read-level pass and the primary table share a read set.
    excluded = sum(s.get('reads_excluded_by_quality_filter', 0) for s in samples)

    return {
        'has_resolution': has_resolution,
        'pct_species': pct_species,
        'mean_support': mean_support,
        'consensus_tau': params.get('consensus_tau', 0.9),
        'split_read_pct': split_pct,
        'split_label': split_label,
        'has_split': split_pct is not None,
        'chimera_rate_refined': chimera_refined,
        'chimera_refined_active': chimera_refined is not None,
        'em': em_info,
        'reads_excluded_by_quality_filter': excluded,
        'quality_pass_reads': tot_reads,
    }


def generate_confusion_html(mapping_data, df_otu=None, top_n=20):
    """HTML table of the taxonomic confusion network aggregated across samples.

    The weight is the number of reads actually CONFOUNDED (i.e. whose consensus
    had a competing taxon carrying real mass), not the OTU's total read count.

    When ``df_otu`` is supplied, the species that OTU was assigned to by PRIMARY
    mapping is shown beside its ID — otherwise the reader has to look up an
    accession|SH code by hand to find out which organism is being confused.
    """
    edges = {}
    for s in mapping_data.get('samples', []):
        tq = s.get('taxonomic_quality')
        if not tq:
            continue
        for edge in tq.get('top_confusion', []):
            key = (edge.get('otu', ''), edge.get('confounder', ''))
            if not key[0] or not key[1]:
                continue
            edges[key] = edges.get(key, 0) + int(edge.get('confounded_reads', 0))
    edges = {k: v for k, v in edges.items() if v > 0}
    if not edges:
        return None

    # OTU_ID -> species assigned by primary mapping
    species_of = {}
    if df_otu is not None and 'Species' in df_otu.columns:
        species_of = (df_otu['Species'].fillna('').astype(str)).to_dict()
        if 'Genus' in df_otu.columns:
            genus = df_otu['Genus'].fillna('').astype(str).to_dict()
            for k, v in list(species_of.items()):
                if not v.strip():
                    species_of[k] = (genus.get(k, '') + ' sp.').strip()

    rows = sorted(edges.items(), key=lambda kv: -kv[1])[:top_n]
    recs = []
    for (otu, conf), n in rows:
        rec = {'OTU': otu}
        if species_of:
            rec['Primary assignment'] = species_of.get(otu, '(not in table)')
        rec['Confounded with'] = conf
        rec['Confounded reads'] = n
        recs.append(rec)
    return pd.DataFrame(recs).to_html(
        classes="table table-striped table-hover table-sm", index=False, border=0)


def generate_lowmapq_html(df_otu, mapq_below=30.0, min_rel_abund=0.01, top_n=10):
    """Screening: OTU abbondanti con MAPQ medio basso — possibile gap di database.

    Calibrazione su 6 mock a composizione nota (TaxQuality_calibrazione.md): le
    metriche di consenso NON distinguono i falsi positivi "concordi" — read che
    concordano con confidenza sulla reference sbagliata perche' quella giusta
    manca dal database (AUROC 0.62-0.78).  mean_mapq pesata per abbondanza li
    separa invece quasi perfettamente (AUROC 0.97): senza la reference vera le
    read si spartiscono fra parenti quasi equivalenti e minimap2 abbassa il
    MAPQ.  Lista di screening ordinata per MAPQ crescente — un aiuto alla
    verifica, non un verdetto.
    """
    if df_otu is None or df_otu.empty or 'mean_mapq' not in df_otu.columns:
        return None
    sample_cols = _sample_columns(df_otu)
    if not sample_cols:
        return None
    counts = df_otu[sample_cols].apply(pd.to_numeric, errors='coerce').fillna(0)
    tot = counts.sum(axis=1)
    grand = float(tot.sum())
    if grand <= 0:
        return None
    rel = tot / grand
    mapq = pd.to_numeric(df_otu['mean_mapq'], errors='coerce')
    mask = (rel >= min_rel_abund) & mapq.notna() & (mapq < mapq_below)
    if not mask.any():
        return None
    sel = df_otu[mask]
    disp = pd.DataFrame({
        'Species': sel['Species'].fillna('') if 'Species' in sel.columns else '',
        'Reads': tot[mask].astype(int),
        'Rel. abundance (%)': (rel[mask] * 100).round(2),
        'Mean MAPQ': mapq[mask].round(1),
        'pct_species': pd.to_numeric(sel.get('pct_species'), errors='coerce').round(1),
        'mean_support': pd.to_numeric(sel.get('mean_support'), errors='coerce').round(2),
    }, index=sel.index)
    disp.index.name = 'OTU_ID'
    disp = disp.sort_values('Mean MAPQ').head(top_n)
    return disp.to_html(classes="table table-striped table-hover table-sm",
                        index=True, border=0)


def generate_mapping_graphs(mapping_data):
    """Generate mapping QC bar charts: mapped/unmapped per sample and quality filter retention."""
    samples_list = mapping_data.get('samples', [])
    if not samples_list:
        return None, None

    df = pd.DataFrame(samples_list)

    # Chart 1: Mapped vs unmapped reads per sample
    df['unmapped'] = df['total_reads'] - df['mapped_unfiltered']
    df_long = df.melt(
        id_vars=['sample'],
        value_vars=['mapped_unfiltered', 'unmapped'],
        var_name='Read Type', value_name='Reads'
    )
    df_long['Read Type'] = df_long['Read Type'].replace({
        'mapped_unfiltered': 'Mapped', 'unmapped': 'Unmapped'
    })
    fig_mapping = px.bar(
        df_long, x='sample', y='Reads', color='Read Type',
        title='Mapping Results per Sample (Mapped vs. Unmapped)',
        labels={'sample': 'Sample', 'Reads': 'Number of Reads'},
        color_discrete_map={'Mapped': '#1f77b4', 'Unmapped': '#aec7e8'},
        barmode='stack'
    )
    fig_mapping_div = pio.to_html(fig_mapping, full_html=False, include_plotlyjs='cdn')

    # Chart 2: Quality filter retention (only if quality filter was active)
    params = mapping_data.get('parameters', {})
    quality_filter_active = params.get('min_percent_identity', 0) > 0 or params.get('min_ref_coverage', 0) > 0
    fig_quality_div = None
    if quality_filter_active and 'mapped_filtered' in df.columns:
        df['reads_removed_by_filter'] = df['mapped_unfiltered'] - df['mapped_filtered']
        df_qlong = df.melt(
            id_vars=['sample'],
            value_vars=['mapped_filtered', 'reads_removed_by_filter'],
            var_name='Category', value_name='Reads'
        )
        df_qlong['Category'] = df_qlong['Category'].replace({
            'mapped_filtered': 'Passed Quality Filter',
            'reads_removed_by_filter': 'Removed by Quality Filter'
        })
        title_parts = []
        if params.get('min_percent_identity', 0) > 0:
            title_parts.append(f"Identity ≥ {params['min_percent_identity']}%")
        if params.get('min_ref_coverage', 0) > 0:
            title_parts.append(f"Ref Coverage ≥ {params['min_ref_coverage']}%")
        filter_desc = " | ".join(title_parts)
        fig_quality = px.bar(
            df_qlong, x='sample', y='Reads', color='Category',
            title=f'Alignment Quality Filter per Sample ({filter_desc})',
            labels={'sample': 'Sample', 'Reads': 'Mapped Reads'},
            color_discrete_map={
                'Passed Quality Filter': '#2ca02c',
                'Removed by Quality Filter': '#d62728'
            },
            barmode='stack'
        )
        fig_quality_div = pio.to_html(fig_quality, full_html=False, include_plotlyjs=False)

    return fig_mapping_div, fig_quality_div


