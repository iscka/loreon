# Column names produced by the split in ResultsReader
_RANK_COLUMNS = ['Kingdom', 'Phylum', 'Class', 'Order', 'Family', 'Genus', 'Species', 'Details']

# Per-OTU taxonomic-quality columns (Feature A).  These are METADATA and must
# never be mistaken for sample abundance columns: doing so added them to the
# composition chart's sample list and, because `qual_n_reads` is itself a read
# count, inflated per-OTU row totals non-uniformly, biasing the top-25 heatmap
# ranking and the Sankey. Imported from ResultsReader so the two cannot drift.
try:
    from ResultsReader import QUALITY_COLUMNS as _QUALITY_COLUMNS
except Exception:  # pragma: no cover - report can run standalone
    _QUALITY_COLUMNS = [
        'pct_species', 'pct_genus', 'pct_above_genus', 'pct_unresolved',
        'resolution_rank', 'resolution_depth_mode', 'mean_support',
        'mean_mapq', 'top_confounder', 'confounded_reads', 'qual_n_reads']

# Everything that is not an abundance column.
_META_COLUMNS = {'Taxonomy'} | set(_RANK_COLUMNS) | set(_QUALITY_COLUMNS)


def _sample_columns(df_otu):
    """Abundance (sample) columns of an OTU table, excluding all metadata."""
    return [c for c in df_otu.columns if c not in _META_COLUMNS]


def _extract_ranks_vectorized(df_otu, sample_cols):
    """Extract Family/Genus/Species for all rows.

    If the OTU table already contains the pre-split rank columns
    (Kingdom … Details), use them directly.  Otherwise fall back to
    the legacy semicolon-split approach for backward compatibility.
    """
    ranks = {}
    pre_split = all(col in df_otu.columns for col in ('Family', 'Genus', 'Species'))

    if pre_split:
        # --- New path: use pre-split columns directly ---
        for rank_name in ('Family', 'Genus', 'Species'):
            ranks[rank_name] = (
                df_otu[rank_name]
                .fillna('')
                .replace('', 'Unclassified')
            )
    else:
        # --- Legacy fallback: parse the Taxonomy string ---
        tax_series = df_otu['Taxonomy'].fillna('')

        def _clean_split(tax_str):
            if not isinstance(tax_str, str):
                return []
            return [p for p in tax_str.split(';')
                    if p and not p.lower().startswith('unclassified')]

        split_lists = tax_series.apply(_clean_split)

        def _get_rank(parts_list, position):
            try:
                if len(parts_list) >= abs(position):
                    return parts_list[position]
            except (IndexError, TypeError):
                pass
            return 'Unclassified'

        for rank_name, pos in [('Family', -3), ('Genus', -2), ('Species', -1)]:
            ranks[rank_name] = split_lists.apply(
                lambda p, po=pos: _get_rank(p, po)
            )

    return ranks


def aggregate_by_rank(df_otu, sample_cols, rank_col, rank_name, top_n=15):
    """Aggregate OTU counts by a pre-computed rank column."""
    print(f"Aggregating for {rank_name}...")

    df_agg = df_otu.groupby(rank_col)[sample_cols].sum()
    df_agg['Total'] = df_agg.sum(axis=1)
    df_agg = df_agg.sort_values(by='Total', ascending=False)

    if len(df_agg) > top_n:
        df_top = df_agg.head(top_n - 1)
        df_others = df_agg.tail(len(df_agg) - (top_n - 1)).sum().to_frame().T
        df_others.index = [f'Others ({rank_name})']
        df_agg = pd.concat([df_top, df_others])

    df_agg = df_agg.drop(columns='Total')
    df_rel = df_agg.div(df_agg.sum(axis=0), axis=1) * 100
    df_rel.index.name = rank_name

    df_long = df_rel.reset_index().melt(
        id_vars=rank_name,
        var_name='Sample',
        value_name='Relative Abundance (%)'
    )
    df_long = df_long.rename(columns={rank_name: 'Taxonomy'})
    df_long['Rank'] = rank_name
    return df_long


def generate_sankey(df_otu):
    """Build Sankey data with per-row lineage information for interactive filtering.

    Returns a JSON string containing:
      - lineages: list of {Kingdom, Phylum, ..., Species, count} per OTU row
      - rankColors: color mapping per rank level
    The actual Sankey rendering and filtering is done in JavaScript (template.html).
    Returns None if no valid data.
    """
    print("Generating Lineages Sankey data...")

    # Determine which rank columns are available
    sankey_ranks = ['Kingdom', 'Phylum', 'Class', 'Order', 'Family', 'Genus', 'Species']
    pre_split = all(r in df_otu.columns for r in sankey_ranks)

    sample_cols = _sample_columns(df_otu)

    if pre_split:
        rank_series = {r: df_otu[r].fillna('').replace('', 'Unclassified') for r in sankey_ranks}
    elif 'Taxonomy' in df_otu.columns:
        tax_parts = df_otu['Taxonomy'].fillna('').apply(
            lambda t: [p.strip().replace('_', ' ') for p in t.split(';') if p.strip()] if isinstance(t, str) else []
        )
        rank_series = {}
        for idx, rank in enumerate(sankey_ranks):
            rank_series[rank] = tax_parts.apply(
                lambda p, i=idx: p[i] if len(p) > i else 'Unclassified'
            )
    else:
        return None

    # Compute total counts per OTU row
    counts = df_otu[sample_cols].apply(pd.to_numeric, errors='coerce').fillna(0).sum(axis=1)

    # Build per-row lineage records (one per OTU)
    lineages = []
    for idx in df_otu.index:
        row_count = int(counts.get(idx, 0))
        if row_count <= 0:
            continue
        record = {rank: rank_series[rank].get(idx, 'Unclassified') for rank in sankey_ranks}
        # Skip rows where all ranks are unclassified
        if all(v == 'Unclassified' for v in record.values()):
            continue
        record['count'] = row_count
        lineages.append(record)

    if not lineages:
        print("WARNING: No valid lineage data found for Sankey.", file=sys.stderr)
        return None

    rank_colors = {
        'Kingdom': 'rgba(31,119,180,0.7)',
        'Phylum':  'rgba(255,127,14,0.7)',
        'Class':   'rgba(44,160,44,0.7)',
        'Order':   'rgba(214,39,40,0.7)',
        'Family':  'rgba(148,103,189,0.7)',
        'Genus':   'rgba(140,86,75,0.7)',
        'Species': 'rgba(227,119,194,0.7)',
    }

    sankey_data = {
        'lineages': lineages,
        'ranks': sankey_ranks,
        'rankColors': rank_colors,
    }

    return json.dumps(sankey_data)


def build_composition_json(df_otu):
    """Family/Genus/Species relative-abundance records for one OTU table.

    Factored out of generate_otu_data_json so the EM table can be rendered
    through exactly the same aggregation path as the primary table — otherwise
    the two series in the comparison view would not be like-for-like."""
    if df_otu is None or df_otu.empty:
        return None
    has_tax = 'Taxonomy' in df_otu.columns or 'Family' in df_otu.columns
    if not has_tax:
        return None
    sample_cols = _sample_columns(df_otu)
    if not sample_cols:
        return None
    df = df_otu.copy()
    df[sample_cols] = df[sample_cols].apply(pd.to_numeric, errors='coerce').fillna(0)
    ranks = _extract_ranks_vectorized(df, sample_cols)
    parts = [
        aggregate_by_rank(df, sample_cols, ranks['Family'], 'Family', top_n=20),
        aggregate_by_rank(df, sample_cols, ranks['Genus'], 'Genus', top_n=15),
        aggregate_by_rank(df, sample_cols, ranks['Species'], 'Species', top_n=15),
    ]
    return pd.concat(parts, ignore_index=True).to_json(orient='records')


def generate_otu_data_json(df_otu):
    print("Generating taxonomic data (Family, Genus, Species)...")

    # Check for taxonomy data (either single column or pre-split columns)
    has_taxonomy = 'Taxonomy' in df_otu.columns or 'Family' in df_otu.columns
    if not has_taxonomy:
        print("WARNING: No taxonomy columns found. Skipping OTU graphs.", file=sys.stderr)
        return "null", None

    # Exclude all taxonomy/quality metadata columns from sample columns
    sample_cols = _sample_columns(df_otu)

    # Ensure sample columns are numeric (DuckDB/XLSX can leave object dtype)
    df_otu[sample_cols] = df_otu[sample_cols].apply(pd.to_numeric, errors='coerce').fillna(0).astype(int)

    # OPT-9: Single-pass taxonomy extraction for all ranks
    ranks = _extract_ranks_vectorized(df_otu, sample_cols)

    df_family = aggregate_by_rank(df_otu, sample_cols, ranks['Family'], 'Family', top_n=20)
    df_genus = aggregate_by_rank(df_otu, sample_cols, ranks['Genus'], 'Genus', top_n=15)
    df_species = aggregate_by_rank(df_otu, sample_cols, ranks['Species'], 'Species', top_n=15)

    df_all_ranks = pd.concat([df_family, df_genus, df_species], ignore_index=True)

    composition_json_data = df_all_ranks.to_json(orient='records')

    print("Generating Heatmap graph...")
    df_counts_only = df_otu[sample_cols]
    top_25_otus = df_counts_only.sum(axis=1).nlargest(25).index
    df_top25 = df_counts_only.loc[top_25_otus]
    df_top25_log = np.log1p(df_top25)

    # Use Species names as Y-axis labels instead of OTU IDs
    if 'Species' in df_otu.columns:
        species_labels = df_otu.loc[top_25_otus, 'Species'].fillna('').replace('', 'Unknown')
        # Disambiguate duplicate species by appending OTU ID
        seen = {}
        y_labels = []
        for otu_id, sp in zip(top_25_otus, species_labels):
            seen[sp] = seen.get(sp, 0) + 1
            if seen[sp] > 1:
                y_labels.append(f"{sp} ({otu_id})")
            else:
                y_labels.append(sp)
        # Second pass: also tag the first occurrence if duplicated
        for i, sp in enumerate(species_labels):
            if seen[sp] > 1 and '(' not in y_labels[i]:
                y_labels[i] = f"{sp} ({top_25_otus[i]})"
    else:
        y_labels = list(top_25_otus)

    fig_heatmap = px.imshow(
        df_top25_log, title="Top 25 Species Heatmap (Log-normalized Abundance)",
        labels=dict(x="Sample", y="Species", color="Log(Count+1)"),
        x=df_top25_log.columns, y=y_labels,
        aspect="auto", height=700
    )
    fig_heatmap_div = pio.to_html(fig_heatmap, full_html=False, include_plotlyjs=False)

    return composition_json_data, fig_heatmap_div


def generate_em_comparison_html(otu_path, em_path, top_n=25):
    """Compare primary counts against EM fractional counts per OTU.

    Surfaces what the EM actually changed — without this the _EM table was
    written to disk and never referenced anywhere in the report."""
    if not em_path:
        return None, None
    em_p = Path(em_path)
    em_tsv = em_p.with_suffix('.tsv')
    src = em_tsv if em_tsv.exists() else em_p
    if not src.exists():
        return None, None
    try:
        df_em = (pd.read_csv(src, sep='\t', index_col=0) if src.suffix == '.tsv'
                 else pd.read_excel(src, index_col=0))
        otu_p = Path(otu_path)
        otu_tsv = otu_p.with_suffix('.tsv')
        osrc = otu_tsv if otu_tsv.exists() else otu_p
        df_pr = (pd.read_csv(osrc, sep='\t', index_col=0) if osrc.suffix == '.tsv'
                 else pd.read_excel(osrc, index_col=0))
    except Exception as e:
        print(f"WARNING: cannot read EM comparison tables: {e}", file=sys.stderr)
        return None, None

    sc_em = _sample_columns(df_em)
    sc_pr = _sample_columns(df_pr)
    if not sc_em or not sc_pr:
        return None, None

    prim = df_pr[sc_pr].apply(pd.to_numeric, errors='coerce').fillna(0).sum(axis=1)
    emc = df_em[sc_em].apply(pd.to_numeric, errors='coerce').fillna(0).sum(axis=1)
    comp = pd.DataFrame({'Primary count': prim, 'EM count': emc}).fillna(0)
    comp['Shift'] = comp['EM count'] - comp['Primary count']
    label_col = 'Species' if 'Species' in df_pr.columns else None
    if label_col is not None:
        comp.insert(0, 'Species', df_pr[label_col].reindex(comp.index).fillna(''))

    totals = {
        'primary_total': float(prim.sum()),
        'em_total': float(emc.sum()),
        'n_otu_primary': int((prim > 0).sum()),
        'n_otu_em': int((emc > 0).sum()),
        'moved': float(comp['Shift'].abs().sum() / 2.0),
        'moved_pct': (round(comp['Shift'].abs().sum() / 2.0 / prim.sum() * 100, 2)
                      if prim.sum() else 0.0),
    }

    shown = comp.reindex(comp['Shift'].abs().sort_values(ascending=False).index).head(top_n)
    shown = shown[shown['Shift'].abs() > 1e-9]
    if shown.empty:
        return None, totals
    for c in ('Primary count', 'EM count', 'Shift'):
        shown[c] = shown[c].round(2)
    return shown.to_html(classes="table table-striped table-hover table-sm",
                         border=0), totals


